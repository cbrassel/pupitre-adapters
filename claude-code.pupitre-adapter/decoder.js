// Décodage par type de ligne

function _sessionMeta(d) {
  if (typeof d.sessionId !== "string") return null;
  return _event(d, "session.meta", {
    sessionId: d.sessionId,
    cwd: _str(d.cwd) || undefined,
    gitBranch: _str(d.gitBranch) || undefined,
    cliVersion: _str(d.version) || undefined
  });
}

// Titre généré par Claude Code : ligne {"type":"ai-title","aiTitle":"…","sessionId":"…"} (sans uuid ni timestamp),
// répétée dans le fichier. Extension optionnelle session.meta.title.
function _aiTitle(d) {
  var t = _str(d.aiTitle);
  if (t === null || t.trim() === "" || typeof d.sessionId !== "string") return null;
  return _event(d, "session.meta", { sessionId: d.sessionId, title: _truncate(t.trim(), 200) });
}

function _decodeUser(d, ctx) {
  var msg = d.message;
  if (!_isObj(msg)) return [];
  var content = msg.content;
  var origin = d.origin;
  var text = typeof content === "string" ? content : null;
  if (Array.isArray(content)) {
    var tparts = [];
    for (var i = 0; i < content.length; i++) {
      var b = content[i];
      if (_isObj(b) && b.type === "text" && typeof b.text === "string") tparts.push(b.text);
    }
    text = tparts.join("\n");
  }

  // Fin d'un sous-agent : rapport transmis (isMeta) ou notification de tâche.
  var hb = _handbackEvent(d, _isObj(origin) ? origin : null, text);
  if (hb) return [hb];
  if ((_isObj(origin) && origin.kind === "task-notification") ||
      (typeof text === "string" && text.replace(/^\s+/, "").indexOf("<task-notification>") === 0)) {
    var tn = _taskNotificationEvent(d, text || "");
    return tn ? [tn] : [];
  }

  if (d.isMeta === true || d.isCompactSummary === true) return [];

  if (typeof content === "string") {
    var ev = _classifyUserText(d, content, 0, null);
    return ev ? [ev] : [];
  }
  if (!Array.isArray(content)) return [];

  var out = [];
  var images = 0, hasToolResult = false;
  var resultBlocks = [];
  for (var j = 0; j < content.length; j++) {
    var blk = content[j];
    if (!_isObj(blk)) continue;
    if (blk.type === "tool_result") { hasToolResult = true; resultBlocks.push(blk); }
    else if (blk.type === "image") images++;
  }

  var tur = _isObj(d.toolUseResult) ? d.toolUseResult : null;
  for (var r = 0; r < resultBlocks.length; r++) {
    var rb = resultBlocks[r];
    var fields = {
      toolUseId: _str(rb.tool_use_id),
      isError: rb.is_error === true,
      text: _truncate(_contentText(rb.content), MAX_RESULT_TEXT)
    };
    // Extension : lancement asynchrone d'un sous-agent (le résultat n'est qu'un accusé).
    if (tur && resultBlocks.length === 1) {
      if (typeof tur.agentId === "string") fields.agentId = tur.agentId;
      if (tur.isAsync === true || tur.status === "async_launched") fields.async = true;
    }
    out.push(_event(d, "tool.result", fields));
  }

  if (typeof text === "string" && text.trim() !== "" || (!hasToolResult && images > 0)) {
    var t = text || "";
    var isInterrupt = t.replace(/^\s+/, "").indexOf("[Request interrupted by user") === 0;
    if (!hasToolResult || isInterrupt) {
      var e2 = _classifyUserText(d, t, images, null);
      if (e2) out.push(e2);
    }
  }
  return out;
}

function _toolTarget(name, input) {
  if (!_isObj(input)) return null;
  switch (name) {
    case "Read": case "Edit": case "Write": case "MultiEdit":
      return _str(input.file_path) || _str(input.path);
    case "NotebookEdit": case "NotebookRead":
      return _str(input.notebook_path) || _str(input.file_path);
    case "Bash": case "PowerShell":
      return _oneLine(_str(input.command), MAX_TARGET);
    case "Grep": case "Glob":
      return _str(input.pattern);
    case "WebFetch":
      return _str(input.url);
    case "WebSearch":
      return _str(input.query);
    case "Skill":
      return _str(input.skill);
    default:
      return null;
  }
}

function _fileChange(name, input) {
  if (!_isObj(input)) return undefined;
  var path = _str(input.file_path);
  if (path === null) return undefined;
  if (name === "Write") {
    return { path: path, added: _countLines(_str(input.content) || "") };
  }
  if (name === "Edit") {
    var fc = { path: path };
    if (typeof input.new_string === "string") fc.added = _countLines(input.new_string);
    if (typeof input.old_string === "string") fc.removed = _countLines(input.old_string);
    return fc;
  }
  if (name === "MultiEdit") {
    var a = 0, rm = 0;
    if (Array.isArray(input.edits)) {
      for (var i = 0; i < input.edits.length; i++) {
        var e = input.edits[i];
        if (!_isObj(e)) continue;
        a += _countLines(_str(e.new_string) || "");
        rm += _countLines(_str(e.old_string) || "");
      }
    }
    return { path: path, added: a, removed: rm };
  }
  return undefined;
}

function _isTrue(v) { return v === true || v === "true"; }

function _decodeAssistant(d, ctx) {
  var msg = d.message;
  if (!_isObj(msg)) return [];
  var messageId = _str(msg.id) || _str(d.uuid);
  var model = _str(msg.model) || undefined;
  var out = [];
  var content = msg.content;
  if (typeof content === "string") content = [{ type: "text", text: content }];
  if (Array.isArray(content)) {
    for (var i = 0; i < content.length; i++) {
      var b = content[i];
      if (!_isObj(b)) continue;
      if (b.type === "text") {
        if (typeof b.text === "string" && b.text.trim() !== "") {
          out.push(_event(d, "assistant.text", { messageId: messageId, text: b.text, model: model }));
        }
      } else if (b.type === "thinking") {
        // Les versions récentes enregistrent souvent une réflexion vide (seule la signature est gardée).
        if (typeof b.thinking === "string" && b.thinking.trim() !== "") {
          out.push(_event(d, "assistant.thinking", { messageId: messageId, text: b.thinking }));
        }
      } else if (b.type === "tool_use") {
        var name = _str(b.name) || "";
        var input = _isObj(b.input) ? b.input : {};
        if (name === "Agent" || name === "Task") {
          out.push(_event(d, "agent.start", {
            messageId: messageId,
            toolUseId: _str(b.id),
            agentType: _str(input.subagent_type) || "general-purpose",
            description: _str(input.description) || "",
            prompt: _str(input.prompt) || undefined,
            background: _isTrue(input.run_in_background)
          }));
        } else {
          out.push(_event(d, "tool.call", {
            messageId: messageId,
            toolUseId: _str(b.id),
            name: name,
            target: _toolTarget(name, input),
            fileChange: _fileChange(name, input)
          }));
        }
      }
    }
  }
  var u = msg.usage;
  if (_isObj(u)) {
    var num = function (v) { return typeof v === "number" && isFinite(v) ? v : undefined; };
    out.push(_event(d, "assistant.usage", {
      messageId: messageId,
      model: model,
      inputTokens: num(u.input_tokens),
      outputTokens: num(u.output_tokens),
      cacheReadTokens: num(u.cache_read_input_tokens),
      cacheCreationTokens: num(u.cache_creation_input_tokens)
    }));
  }
  return out;
}

function _decodeSystem(d, ctx) {
  // Commandes locales enregistrées comme lignes system (/skills, /color, /clear en mode -p…).
  if (d.subtype === "local_command" && typeof d.content === "string") {
    var t = d.content.replace(/^\s+/, "");
    if (t.indexOf("<command-name>") === 0) {
      var ev = _commandEvent(d, t);
      return ev ? [ev] : [];
    }
  }
  return [];
}

function _decodeAttachment(d, ctx) {
  var a = d.attachment;
  if (!_isObj(a) || a.type !== "queued_command") return [];
  // Message mis en file pendant un tour et absorbé dans ce tour.
  var origin = _isObj(a.origin) ? a.origin : null;
  var prompt = a.prompt;
  var text = typeof prompt === "string" ? prompt : null;
  var images = 0;
  if (Array.isArray(prompt)) {
    var parts = [];
    for (var i = 0; i < prompt.length; i++) {
      var b = prompt[i];
      if (!_isObj(b)) continue;
      if (b.type === "text" && typeof b.text === "string") parts.push(b.text);
      else if (b.type === "image") images++;
    }
    text = parts.join("\n");
  }
  if (origin && origin.kind === "peer") {
    var hb = _handbackEvent(d, origin, text);
    return hb ? [hb] : [];
  }
  if (a.commandMode === "task-notification" || (origin && origin.kind === "task-notification")) {
    var tn = _taskNotificationEvent(d, text || "");
    return tn ? [tn] : [];
  }
  if (a.commandMode === "prompt" && (!origin || origin.kind === "human")) {
    var ev = _classifyUserText(d, text || "", images, { queued: true });
    return ev ? [ev] : [];
  }
  return [];
}

function _decodeObject(d, ctx) {
  if (!_isObj(d)) return [];
  var role = _isObj(ctx) && ctx.role === "agent" ? "agent" : "main";
  if (role === "main" && d.isSidechain === true) return [];
  var type = d.type;
  var out = [];
  if (type === "user" || type === "assistant" || type === "system") {
    if (role === "main") {
      var meta = _sessionMeta(d);
      if (meta) out.push(meta);
    }
  }
  if (type === "ai-title") {
    if (role !== "main") return [];
    var title = _aiTitle(d);
    return title ? [title] : [];
  }
  var evs;
  if (type === "user") evs = _decodeUser(d, ctx);
  else if (type === "assistant") evs = _decodeAssistant(d, ctx);
  else if (type === "system") evs = _decodeSystem(d, ctx);
  else if (type === "attachment") evs = _decodeAttachment(d, ctx);
  else return [];
  return out.concat(evs);
}

