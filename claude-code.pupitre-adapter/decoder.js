// Adaptateur Pupitre pour Claude Code — decoder.js (adapterApi 1)
//
// Script JavaScript pur : aucune entrée/sortie, aucun require/import, aucun global de Node.
// Il tourne à l'identique dans Node (tests) et dans JavaScriptCore (app).
// Contrat : docs/adapter-api.md. Toute entrée invalide donne [] (ou null), jamais d'exception.
//
// Format observé sur Claude Code 2.1.29x–2.1.325 (voir fixtures/).

// Pas de "use strict" global : les fonctions doivent rester globales quel que soit le mode d'évaluation.

var MAX_RESULT_TEXT = 4000;   // tool.result.text, agent.end.resultText
var MAX_TARGET = 80;          // tool.call.target (commandes Bash…)

// ---------------------------------------------------------------------------
// Utilitaires

function _isObj(v) { return v !== null && typeof v === "object" && !Array.isArray(v); }
function _str(v) { return typeof v === "string" ? v : null; }

function _truncate(s, max) {
  if (typeof s !== "string") return s;
  if (s.length <= max) return s;
  var cut = max - 1;
  // Ne pas couper une paire de substitution UTF-16 (emoji…) : un demi-caractère
  // isolé n'est pas sérialisable de façon identique selon le moteur JS.
  var c = s.charCodeAt(cut - 1);
  if (c >= 0xD800 && c <= 0xDBFF) cut -= 1;
  return s.slice(0, cut) + "…";
}

// Cible courte sur une ligne (commande Bash multi-lignes → première ligne + …).
function _oneLine(s, max) {
  if (typeof s !== "string") return null;
  var t = s.trim();
  var nl = t.indexOf("\n");
  if (nl >= 0) t = t.slice(0, nl).trimEnd() + " …";
  return _truncate(t, max);
}

function _countLines(s) {
  if (typeof s !== "string" || s.length === 0) return 0;
  var n = s.split("\n").length;
  if (s.charAt(s.length - 1) === "\n") n -= 1;   // saut de ligne final
  return n;
}

function _tag(text, name) {
  if (typeof text !== "string") return null;
  var re = new RegExp("<" + name + "(?:\\s[^>]*)?>([\\s\\S]*?)</" + name + ">");
  var m = re.exec(text);
  return m ? m[1] : null;
}

function _base(d) {
  var ev = {};
  ev.uuid = typeof d.uuid === "string" ? d.uuid : null;
  if (typeof d.timestamp === "string") ev.timestamp = d.timestamp;
  return ev;
}

function _event(d, kind, fields) {
  var ev = _base(d);
  ev.kind = kind;
  for (var k in fields) {
    if (Object.prototype.hasOwnProperty.call(fields, k) && fields[k] !== undefined) ev[k] = fields[k];
  }
  // kind en premier pour la lisibilité des expected.json
  var out = { kind: ev.kind, uuid: ev.uuid };
  if (ev.timestamp !== undefined) out.timestamp = ev.timestamp;
  for (var j in ev) {
    if (j !== "kind" && j !== "uuid" && j !== "timestamp") out[j] = ev[j];
  }
  return out;
}

// Texte d'un contenu de tool_result : chaîne ou tableau de blocs (text, image…).
function _contentText(c) {
  if (typeof c === "string") return c;
  if (!Array.isArray(c)) return "";
  var parts = [];
  for (var i = 0; i < c.length; i++) {
    var b = c[i];
    if (_isObj(b) && b.type === "text" && typeof b.text === "string") parts.push(b.text);
  }
  return parts.join("\n");
}

