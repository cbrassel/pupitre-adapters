// Messages « système » déguisés en lignes user

// Préfixes de contenu qui ne sont jamais un vrai message utilisateur.
var NON_PROMPT_PREFIXES = [
  "<local-command-stdout>", "<local-command-stderr>", "<local-command-caveat>",
  "<bash-stdout>", "<bash-stderr>", "<system-reminder>", "<task-notification>",
  "<agent-message", "<cross-session-message", "Another Claude session sent a message:",
  "Caveat: The messages below were generated by the user while running local commands"
];

function _startsWithAny(s, list) {
  for (var i = 0; i < list.length; i++) if (s.indexOf(list[i]) === 0) return true;
  return false;
}

// "/compact" tapé seul : doublon de la ligne <command-name> qui suit.
var BARE_SLASH_RE = /^\/[a-z][a-z0-9:_-]*(?:[ \t][^\n]*)?$/;

function _commandEvent(d, text) {
  var name = _tag(text, "command-name");
  if (name === null) return null;
  name = name.trim();
  var fields = { name: name };
  var args = _tag(text, "command-args");
  if (args !== null && args.trim() !== "") fields.args = args.trim();
  var out = _tag(text, "local-command-stdout");
  if (out !== null && out.trim() !== "") fields.output = _truncate(out.trim(), MAX_RESULT_TEXT);
  return _event(d, "user.command", fields);
}

// Notification de fin de tâche d'arrière-plan. Seules les tâches « agent » donnent agent.end
// (les commandes Bash ou MCP en arrière-plan ont aussi des <task-notification>).
function _taskNotificationEvent(d, text) {
  var body = _tag(text, "task-notification");
  if (body === null) return null;
  var taskId = _tag(body, "task-id");
  var summary = _tag(body, "summary") || "";
  taskId = taskId ? taskId.trim() : null;
  var isAgent = /^Agent\b/.test(summary.trim()) || (taskId !== null && /^a[0-9a-f]{16}$/.test(taskId));
  if (!isAgent) return null;
  // Agent arrêté mais dont les propres tâches de fond tournent encore : pas une fin.
  if (/waiting on its own background work/.test(summary) || /has not reported yet/.test(_tag(body, "result") || "")) return null;
  var status = (_tag(body, "status") || "").trim();
  var fields = {
    status: status === "completed" ? "done" : "failed"
  };
  var toolUseId = _tag(body, "tool-use-id");
  if (toolUseId) fields.toolUseId = toolUseId.trim();
  if (taskId) fields.agentId = taskId;
  var result = _tag(body, "result");
  // « This agent's report was delivered to you as a message… » : simple renvoi vers le hand-back.
  if (result !== null && /report was delivered to you as a message/.test(result)) result = null;
  if (result !== null && result.trim() !== "") fields.resultText = _truncate(result.trim(), MAX_RESULT_TEXT);
  else if (summary.trim() !== "") fields.resultText = _truncate(summary.trim(), MAX_RESULT_TEXT);
  return _event(d, "agent.end", fields);
}

// Rapport final d'un sous-agent (« [Subagent hand-back] ») transmis comme message de pair.
function _handbackEvent(d, origin, text) {
  var from = null, report = null;
  if (_isObj(origin)) {
    if (origin.kind !== "peer" || origin.handback !== true) return null;
    from = _str(origin.from) || _str(origin.senderTaskId);
    report = _str(origin.handbackReportText);
  } else {
    // Sans champ origin (versions plus anciennes) : on se fie au texte.
    if (typeof text !== "string" || text.indexOf("[Subagent hand-back]") < 0 ||
        !/^\s*(Another Claude session sent a message:\s*)?<agent-message from="/.test(text)) return null;
  }
  if (from === null && typeof text === "string") {
    var m = /<agent-message from="([^"]+)"/.exec(text);
    if (m) from = m[1];
  }
  if (report === null && typeof text === "string") {
    var i = text.indexOf("The report follows:\n");
    if (i >= 0) {
      var r = text.slice(i + "The report follows:\n".length);
      var end = r.lastIndexOf("</agent-message>");
      if (end >= 0) r = r.slice(0, end);
      report = r.replace(/^ {2}/gm, "").trim();
    }
  }
  if (from === null) return null;
  var fields = { agentId: from, status: "done" };
  if (report) fields.resultText = _truncate(report, MAX_RESULT_TEXT);
  return _event(d, "agent.end", fields);
}

// Classe un texte saisi côté user (hors tool_result). Renvoie un Event ou null.
function _classifyUserText(d, text, imageCount, extra) {
  if (typeof text !== "string") text = "";
  var t = text.replace(/^\s+/, "");
  if (t.indexOf("[Request interrupted by user") === 0) {
    return _event(d, "user.interrupt", { text: t.trim() });
  }
  if (t.indexOf("<command-name>") === 0 || t.indexOf("<command-message>") === 0) {
    return _commandEvent(d, t);
  }
  if (t.indexOf("<bash-input>") === 0) {
    var cmd = _tag(t, "bash-input");
    return _event(d, "user.command", { name: "!", args: cmd !== null ? cmd.trim() : undefined });
  }
  if (t.indexOf("<task-notification>") === 0) return _taskNotificationEvent(d, t);
  if (_startsWithAny(t, NON_PROMPT_PREFIXES)) return null;
  if (imageCount === 0 && BARE_SLASH_RE.test(t.trim())) return null;
  if (t.trim() === "" && imageCount === 0) return null;
  var fields = { text: text.trim(), imageCount: imageCount };
  if (extra) for (var k in extra) fields[k] = extra[k];
  return _event(d, "user.prompt", fields);
}

