// API publique (fonctions globales)

function decodeLine(line, ctx) {
  try {
    if (typeof line !== "string") return [];
    var s = line.trim();
    if (s === "" || s.charAt(0) !== "{") return [];
    var d;
    try { d = JSON.parse(s); } catch (e) { return []; }
    return _decodeObject(d, ctx);
  } catch (e) {
    return [];
  }
}

function decodeFile(text, ctx) {
  try {
    if (typeof text !== "string") return [];
    var lines = text.split("\n");
    var out = [];
    for (var i = 0; i < lines.length; i++) {
      var evs = decodeLine(lines[i], ctx);
      for (var j = 0; j < evs.length; j++) out.push(evs[j]);
    }
    return out;
  } catch (e) {
    return [];
  }
}

function decodeAgentMeta(text) {
  try {
    if (typeof text !== "string") return null;
    var d;
    try { d = JSON.parse(text); } catch (e) { return null; }
    if (!_isObj(d)) return null;
    var out = {
      agentType: _str(d.agentType) || "general-purpose",
      description: _str(d.description) || "",
      toolUseId: _str(d.toolUseId)
    };
    if (typeof d.agentId === "string") out.agentId = d.agentId;
    // Extensions optionnelles (voir docs/adapter-api.md)
    if (typeof d.requestShape === "string") out.background = d.requestShape === "background";
    if (typeof d.finished === "boolean") out.finished = d.finished;
    if (typeof d.model === "string") out.model = d.model;
    return out;
  } catch (e) {
    return null;
  }
}

function discover(paths) {
  try {
    if (!Array.isArray(paths)) return [];
    var set = {};
    for (var i = 0; i < paths.length; i++) if (typeof paths[i] === "string") set[paths[i]] = true;
    var out = [];
    for (var j = 0; j < paths.length; j++) {
      var p = paths[j];
      if (typeof p !== "string") continue;
      var slash = p.lastIndexOf("/");
      var dir = slash >= 0 ? p.slice(0, slash + 1) : "";
      var base = slash >= 0 ? p.slice(slash + 1) : p;
      var m = /^agent-(.+)\.jsonl$/.exec(base);
      if (!m) continue;
      var item = { agentId: m[1], transcript: p };
      var metaPath = dir + "agent-" + m[1] + ".meta.json";
      if (set[metaPath]) item.meta = metaPath;
      out.push(item);
    }
    return out;
  } catch (e) {
    return [];
  }
}

